# Задача 4. Попадание точки в заштрихованную область.
# Область = круг радиуса 1 с центром в (0; 0)
#           + треугольник с вершинами (-2; 0), (0; 0), (0; -2).
# Границы входят в область (поэтому везде <= и >=).

x = float(input())
y = float(input())

in_circle = x * x + y * y <= 1
in_triangle = x <= 0 and y <= 0 and x + y >= -2

if in_circle or in_triangle:
    print("Да")
else:
    print("Нет")
